import type { SidebarsConfig } from "@docusaurus/plugin-content-docs"

const group = (label: string, dirName: string) => ({
  type: "category" as const,
  label,
  collapsible: false,
  items: [{ type: "autogenerated" as const, dirName }]
})

const componentGroups: ReadonlyArray<readonly [string, string]> = [
  ["Layout", "layout"],
  ["Inputs", "inputs"],
  ["Combobox", "combobox"],
  ["Buttons", "buttons"],
  ["Navigation", "navigation"],
  ["Feedback", "feedback"],
  ["Overlays", "overlays"],
  ["Data display", "data-display"],
  ["Typography", "typography"],
  ["Miscellaneous", "miscellaneous"],
  ["Extensions", "extensions"],
  ["Charts", "charts"],
  ["Hooks", "hooks"],
  ["Dates", "dates"],
  ["Code highlight", "code-highlight"],
  ["Form", "form"],
  ["Schedule", "schedule"],
  ["Data table", "data-table"],
  ["Rich text editor", "tiptap"]
]

const sidebars: SidebarsConfig = {
  started: [{ type: "category", label: "Overview", collapsible: false, items: ["index", "icons"] }],
  theming: [group("Theming", "theming"), group("Styles", "styling")],
  components: componentGroups.map(([label, dirName]) => group(label, dirName))
}

export default sidebars
